package application.module.logging.context;

import java.util.Locale;
import java.util.Map;
import java.util.Properties;
import java.util.TreeMap;

/**
 * Pure resolver that turns the layered node-logging configuration (L0/L1/L2,
 * plan §8) into the <b>generated</b> Log4j2 .properties content for the two
 * runtime contexts (per-node isolated LoggerContext plan, §8.3, §6.4).
 * <p>
 * This class is a <b>pure function</b>: it performs no I/O and no logging.
 * The caller loads the layer files into {@link Properties} and passes them in
 * via {@link Layers}; file writing is the job of {@link NodeLoggingConfigWriter}.
 * </p>
 *
 * <h3>Resolution chain (plan §8.1)</h3>
 * <ul>
 *   <li><b>node root level</b>: {@code node.level} in L2 &rarr; L1 &rarr; L0-node &rarr;
 *       global root (L0-global {@code level}, hardcoded fallback INFO)</li>
 *   <li><b>node motor class</b> {@code C}: {@code C.level} in L2 &rarr; L1 &rarr;
 *       L0-node &rarr; L0-global; when no layer has an opinion, no entry is
 *       emitted (the class inherits the node root via the Log4j2 hierarchy)</li>
 *   <li><b>global class</b> {@code G}: {@code G.level} in L1 &rarr; L0-node &rarr;
 *       L0-global; same "only when overridden" rule against the global root</li>
 * </ul>
 *
 * <h3>Class ownership (deterministic, package affiliation — plan §8.2)</h3>
 * {@code application.module.node.**} is <b>node motor</b> except the
 * {@code node.gui.}, {@code node.profile.} and {@code node.logging.} prefixes
 * (GUI/profile/logging infrastructure belongs to the global context); every
 * other class name is <b>global</b>.
 *
 * <h3>Level names (JUL name spacing — plan §8.2)</h3>
 * The stored layers keep JUL names for compatibility; {@link #toLog4jLevel}
 * maps them (and passes Log4j2 names through): FINEST/ALL&rarr;TRACE,
 * FINER/FINE&rarr;DEBUG, CONFIG/INFO&rarr;INFO, WARNING/WARN&rarr;WARN,
 * SEVERE/ERROR&rarr;ERROR, OFF&rarr;OFF, unrecognised&rarr;INFO.
 *
 * <h3>Keys that are deliberately dropped</h3>
 * JUL-only keys have no Log4j2 meaning and are never rendered: {@code handlers},
 * {@code .level} (the JUL root), {@code java.util.logging.*} (JUL handler
 * config), {@code node.gui.consoleLogSize} (GUI bus setting, consumed from the
 * effective properties elsewhere). {@code node.fileLog.enable/dir/level} are
 * consumed for the node RollingFile appender, not as logger entries.
 */
public final class NodeLoggingConfigResolver {

    /** Node module level key (the node default level, L2 &rarr; L1 &rarr; L0). */
    public static final String KEY_NODE_LEVEL = "node.level";
    /** Global root level key (hardcoded global default layer). */
    public static final String KEY_GLOBAL_LEVEL = "level";
    public static final String KEY_FILE_LOG_ENABLE = "node.fileLog.enable";
    public static final String KEY_FILE_LOG_DIR = "node.fileLog.dir";
    public static final String KEY_FILE_LOG_LEVEL = "node.fileLog.level";
    /** Node file-log rollover size (Log4j2 size syntax, e.g. {@code 10MB}). */
    public static final String KEY_FILE_LOG_SIZE = "node.fileLog.size";
    /** Node file-log maximum number of rolled files to keep. */
    public static final String KEY_FILE_LOG_MAX = "node.fileLog.max";

    /** Deterministic name of the node RollingFile appender in the generated file. */
    public static final String NODE_FILE_APPENDER = "nodefile";
    /** Deterministic name of the node Console appender in the generated file. */
    public static final String NODE_CONSOLE_APPENDER = "console";

    /** File header — the generated files are NOT the source of truth (plan §6.4). */
    public static final String GENERATED_HEADER = "# GENERATED by Node - do not edit";

    /** Default node file-log rollover size (Log4j2 size syntax). */
    public static final String DEFAULT_FILE_LOG_SIZE = "10MB";
    /** Default number of rolled node log files to keep. */
    public static final int DEFAULT_FILE_LOG_MAX = 5;

    /**
     * The line pattern, preserving the BriefLogFormatter shape
     * ({@code idő szint [szál] osztály - üzenet}); the node console appender
     * additionally carries the profile name as a literal prefix (plan §6.4).
     */
    public static final String LINE_PATTERN = "%d{yyyy-MM-dd HH:mm:ss} %-5level [%thread] %logger{1} - %msg%n";

    private NodeLoggingConfigResolver() {
        // pure static utility
    }

    /**
     * The four configuration layers, already loaded into {@link Properties}
     * by the caller (missing files pass as empty {@link Properties}).
     */
    public static final class Layers {
        private final Properties l0Node;
        private final Properties l0Global;
        private final Properties l1;
        private final Properties l2;

        public Layers(Properties l0Node, Properties l0Global, Properties l1, Properties l2) {
            this.l0Node = l0Node != null ? l0Node : new Properties();
            this.l0Global = l0Global != null ? l0Global : new Properties();
            this.l1 = l1 != null ? l1 : new Properties();
            this.l2 = l2 != null ? l2 : new Properties();
        }
    }

    /**
     * The resolved, render-ready configuration of both contexts.
     */
    public static final class Resolved {
        final String nodeRootLevel;
        final Map<String, String> nodeLoggerLevels;
        final String globalRootLevel;
        final Map<String, String> globalLoggerLevels;
        final boolean fileLogEnabled;
        final String fileLogDir;
        final String fileLogLevel; // log4j2 name, or null when not set
        final String fileLogSize;  // Log4j2 size syntax (e.g. "10MB")
        final int fileLogMax;      // rolled files to keep

        Resolved(String nodeRootLevel, Map<String, String> nodeLoggerLevels,
                 String globalRootLevel, Map<String, String> globalLoggerLevels,
                 boolean fileLogEnabled, String fileLogDir, String fileLogLevel,
                 String fileLogSize, int fileLogMax) {
            this.nodeRootLevel = nodeRootLevel;
            this.nodeLoggerLevels = nodeLoggerLevels;
            this.globalRootLevel = globalRootLevel;
            this.globalLoggerLevels = globalLoggerLevels;
            this.fileLogEnabled = fileLogEnabled;
            this.fileLogDir = fileLogDir;
            this.fileLogLevel = fileLogLevel;
            this.fileLogSize = fileLogSize;
            this.fileLogMax = fileLogMax;
        }
    }

    // ── Resolution ──────────────────────────────────────────────────────

    /**
     * Resolves the two generated configurations from the layers.
     *
     * @param layers            the loaded layers (never null)
     * @param defaultFileLogDir fallback for {@code node.fileLog.dir} when no layer
     *                          sets it — the portable <b>relative</b>
     *                          {@code logs/node} by default (the
     *                          {@code node.fileLog.*} L0 defaults carry it, so
     *                          the generated file stays disk-portable); the
     *                          caller may still pass an absolute path when an
     *                          explicit layer value is required
     * @return the resolved configuration (never null)
     */
    public static Resolved resolve(Layers layers, String defaultFileLogDir) {
        String globalRoot = toLog4jLevel(
                valueOr(layers.l0Global, KEY_GLOBAL_LEVEL, "INFO"));

        String nodeDefault = toLog4jLevel(firstNonNull(
                valueOr(layers.l2, KEY_NODE_LEVEL, null),
                valueOr(layers.l1, KEY_NODE_LEVEL, null),
                valueOr(layers.l0Node, KEY_NODE_LEVEL, null),
                globalRoot));

        Map<String, String> nodeLevels = new TreeMap<>();
        Map<String, String> globalLevels = new TreeMap<>();
        Properties mergedL0 = new Properties();
        mergedL0.putAll(layers.l0Global);
        mergedL0.putAll(layers.l0Node); // node-module L0 wins over other-module L0

        for (Properties layer : new Properties[]{layers.l2, layers.l1, mergedL0}) {
            for (String key : layer.stringPropertyNames()) {
                if (!key.endsWith(".level") || !isLoggerKey(key)) {
                    continue;
                }
                String className = key.substring(0, key.length() - ".level".length());
                String value = toLog4jLevel(layer.getProperty(key));
                if (isNodeMotorClass(className)) {
                    nodeLevels.putIfAbsent(className, value);
                } else {
                    globalLevels.putIfAbsent(className, value);
                }
            }
        }

        boolean fileLogEnabled = Boolean.parseBoolean(
                firstNonNull(valueOr(layers.l2, KEY_FILE_LOG_ENABLE, null),
                        valueOr(layers.l1, KEY_FILE_LOG_ENABLE, null),
                        valueOr(layers.l0Node, KEY_FILE_LOG_ENABLE, null), "true"));
        String fileLogDir = firstNonNull(
                valueOr(layers.l2, KEY_FILE_LOG_DIR, null),
                valueOr(layers.l1, KEY_FILE_LOG_DIR, null),
                valueOr(layers.l0Node, KEY_FILE_LOG_DIR, null), defaultFileLogDir);
        String fileLogLevelName = firstNonNull(
                valueOr(layers.l2, KEY_FILE_LOG_LEVEL, null),
                valueOr(layers.l1, KEY_FILE_LOG_LEVEL, null),
                valueOr(layers.l0Node, KEY_FILE_LOG_LEVEL, null));
        String fileLogLevel = fileLogLevelName == null ? null : toLog4jLevel(fileLogLevelName);
        String fileLogSize = firstNonNull(
                valueOr(layers.l2, KEY_FILE_LOG_SIZE, null),
                valueOr(layers.l1, KEY_FILE_LOG_SIZE, null),
                valueOr(layers.l0Node, KEY_FILE_LOG_SIZE, null), DEFAULT_FILE_LOG_SIZE);
        int fileLogMax = parseIntOrDefault(firstNonNull(
                valueOr(layers.l2, KEY_FILE_LOG_MAX, null),
                valueOr(layers.l1, KEY_FILE_LOG_MAX, null),
                valueOr(layers.l0Node, KEY_FILE_LOG_MAX, null)), DEFAULT_FILE_LOG_MAX);

        return new Resolved(nodeDefault, nodeLevels, globalRoot, globalLevels,
                fileLogEnabled, fileLogDir, fileLogLevel, fileLogSize, fileLogMax);
    }

    // ── Rendering (pure text; plan §6.4 syntax facts for log4j 2.26.1) ──

    /**
     * Renders the node context's generated .properties file.
     *
     * @param resolved    the resolved configuration
     * @param profileName the node profile name (used as the log file base name
     *                    and as the console line prefix)
     * @return the full file content
     */
    public static String renderNodeProperties(Resolved resolved, String profileName) {
        StringBuilder sb = new StringBuilder();
        appendBase(sb, resolved.nodeRootLevel, resolved.nodeLoggerLevels);
        // Console appender with the node-profile prefix (plan §6.4).
        String consolePattern = LINE_PATTERN.replace("%logger{1}", "[" + profileName + "] %logger{1}");
        sb.append("appender.").append(NODE_CONSOLE_APPENDER).append(".name = ").append(NODE_CONSOLE_APPENDER).append('\n');
        sb.append("appender.").append(NODE_CONSOLE_APPENDER).append(".type = Console\n");
        sb.append("appender.").append(NODE_CONSOLE_APPENDER).append(".layout.type = PatternLayout\n");
        sb.append("appender.").append(NODE_CONSOLE_APPENDER).append(".layout.pattern = ").append(consolePattern).append('\n');
        sb.append("rootLogger.appenderRef.").append(NODE_CONSOLE_APPENDER).append(".ref = ").append(NODE_CONSOLE_APPENDER).append('\n');
        // RollingFile appender (optional via node.fileLog.enable).
        if (resolved.fileLogEnabled) {
            String dir = toForwardSlashes(resolved.fileLogDir);
            boolean trailingSlash = dir.endsWith("/");
            String fileName = (trailingSlash ? dir : dir + "/") + profileName + ".log";
            String filePattern = (trailingSlash ? dir : dir + "/") + profileName + "-%i.log.gz";
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".name = ").append(NODE_FILE_APPENDER).append('\n');
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".type = RollingFile\n");
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".fileName = ").append(fileName).append('\n');
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".filePattern = ").append(filePattern).append('\n');
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".policies.type = Policies\n");
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".policies.size.type = SizeBasedTriggeringPolicy\n");
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".policies.size.size = ").append(resolved.fileLogSize).append('\n');
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".strategy.type = DefaultRolloverStrategy\n");
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".strategy.max = ").append(resolved.fileLogMax).append('\n');
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".layout.type = PatternLayout\n");
            sb.append("appender.").append(NODE_FILE_APPENDER).append(".layout.pattern = ").append(LINE_PATTERN).append('\n');
            sb.append("rootLogger.appenderRef.").append(NODE_FILE_APPENDER).append(".ref = ").append(NODE_FILE_APPENDER).append('\n');
            if (resolved.fileLogLevel != null) {
                sb.append("rootLogger.appenderRef.").append(NODE_FILE_APPENDER).append(".level = ")
                        .append(resolved.fileLogLevel).append('\n');
            }
        }
        return sb.toString();
    }

    /**
     * Renders the global context's generated .properties file. It carries
     * levels only — the System Console bridge is attached programmatically
     * (plan §6.4: the console appender is NOT part of the file).
     *
     * @param resolved the resolved configuration
     * @return the full file content
     */
    public static String renderGlobalProperties(Resolved resolved) {
        StringBuilder sb = new StringBuilder();
        appendBase(sb, resolved.globalRootLevel, resolved.globalLoggerLevels);
        return sb.toString();
    }

    private static void appendBase(StringBuilder sb, String rootLevel, Map<String, String> loggerLevels) {
        sb.append(GENERATED_HEADER).append('\n');
        sb.append("status = ERROR\n");
        sb.append("configWatch = false\n");
        sb.append("rootLogger.level = ").append(rootLevel).append('\n');
        // P0/P1 spike fact: the 2.26 properties configurator does NOT accept dotted
        // FQCN component paths (logger.com.foo.level -> "No name attribute provided
        // for Logger com") — use un-dotted identifiers with an explicit name key.
        int i = 0;
        for (Map.Entry<String, String> e : loggerLevels.entrySet()) {
            i++;
            sb.append("logger.l").append(i).append(".name = ").append(e.getKey()).append('\n');
            sb.append("logger.l").append(i).append(".level = ").append(e.getValue()).append('\n');
        }
    }

    // ── Helpers (package-visible for the unit tests) ────────────────────

    /**
     * Maps a stored level name (JUL or Log4j2, case-insensitive) to a Log4j2
     * level name; unrecognised values map to INFO (the safe default).
     */
    static String toLog4jLevel(String name) {
        if (name == null || name.isBlank()) {
            return "INFO";
        }
        switch (name.trim().toUpperCase(Locale.ROOT)) {
            case "ALL":
            case "FINEST":
            case "TRACE":
                return "TRACE";
            case "FINER":
            case "FINE":
            case "DEBUG":
                return "DEBUG";
            case "CONFIG":
            case "INFO":
                return "INFO";
            case "WARNING":
            case "WARN":
                return "WARN";
            case "SEVERE":
            case "ERROR":
                return "ERROR";
            case "OFF":
                return "OFF";
            default:
                return "INFO";
        }
    }

    /**
     * Node motor package affiliation (plan §8.2): {@code application.module.node.**}
     * except the {@code gui.}, {@code profile.} and {@code logging.} prefixes.
     */
    static boolean isNodeMotorClass(String className) {
        if (className == null || !className.startsWith("application.module.node.")) {
            return false;
        }
        return !className.startsWith("application.module.node.gui.")
                && !className.startsWith("application.module.node.profile.")
                && !className.startsWith("application.module.node.logging.");
    }

    /**
     * Whether a {@code *.level} key names a logger: it is not the node/global
     * default level key, not a file-log key ({@code node.fileLog.*}), and not
     * JUL handler configuration.
     */
    private static boolean isLoggerKey(String key) {
        String className = key.substring(0, key.length() - ".level".length());
        if (className.isEmpty()) {
            return false; // the JUL root ".level"
        }
        if (className.equals("node") || className.equals("node.fileLog")) {
            return false;
        }
        return !className.startsWith("java.util.logging.");
    }

    private static String valueOr(Properties props, String key, String fallback) {
        String v = props.getProperty(key);
        return (v == null || v.isBlank()) ? fallback : v.trim();
    }

    private static String firstNonNull(String... values) {
        for (String v : values) {
            if (v != null && !v.isBlank()) {
                return v;
            }
        }
        return null;
    }

    /** Parses a positive integer; null, non-numeric or non-positive values yield {@code fallback}. */
    private static int parseIntOrDefault(String value, int fallback) {
        if (value == null) {
            return fallback;
        }
        try {
            int parsed = Integer.parseInt(value.trim());
            return parsed > 0 ? parsed : fallback;
        } catch (NumberFormatException e) {
            return fallback;
        }
    }

    /** The properties configurator treats backslash as an escape (P0 spike) — store forward slashes. */
    private static String toForwardSlashes(String path) {
        return path == null ? "" : path.replace('\\', '/');
    }
}