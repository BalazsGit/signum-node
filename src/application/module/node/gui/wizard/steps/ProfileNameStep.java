package application.module.node.gui.wizard.steps;

import application.module.node.gui.wizard.WizardContext;
import application.module.node.gui.wizard.WizardStep;
import application.module.node.gui.wizard.WizardTexts;
import application.module.node.profile.Network;
import application.module.node.profile.NodeProfileRepository;
import application.module.node.profile.ProfileNameSuggester;
import application.utils.gui.ConfigurationUtils;
import jiconfont.icons.font_awesome.FontAwesome;

import javax.swing.BorderFactory;
import javax.swing.BoxLayout;
import javax.swing.Box;
import javax.swing.ButtonGroup;
import javax.swing.JComponent;
import javax.swing.JPanel;
import javax.swing.JRadioButton;
import javax.swing.JTextField;
import javax.swing.UIManager;
import javax.swing.event.DocumentEvent;
import javax.swing.event.DocumentListener;
import java.awt.Color;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;
import java.util.function.Supplier;

/**
 * Wizard step 1 — the network + the profile name (suggested or custom).
 * <p>
 * The name is decided <b>first</b> (it identifies the profile and its data, and
 * the wizard's title bar shows it live). The <b>network</b> (mainnet / testnet —
 * mocknet is not offered for now; SSOT: {@link Network}) is decided here too,
 * because it is the first component of the suggested name. The suggested name
 * is generated by the
 * SSOT ({@link ProfileNameSuggester}) from the current context (network + engine
 * + ports) with a {@code _01/_02/...} suffix when the base name is taken; a
 * custom name is free text, live-validated (format, reserved, taken). The
 * resolved name is shown under the input as {@code "Profile Name: …"} (the
 * entered name for a custom choice, the live suggested name otherwise).
 * </p>
 * <p>
 * The step mirrors the choice into the shared context live (the controller
 * re-resolves the suggested name on every context change, so the title bar
 * follows the network/engine/port selections of the later steps). The final
 * name lands in {@link WizardContext#setName} on exit / finish.
 * </p>
 */
public class ProfileNameStep implements WizardStep {

    /**
     * The step's root container: it keeps the BoxLayout content
     * <b>top-anchored</b>. The dialog stretches every step panel to the full
     * available height — a bare BoxLayout would hand that extra space to the
     * stretchable text panes (their max height is unbounded), inflating each
     * pane and opening visible blank gaps between the rows (e.g. between the
     * "Profile Name:" line and the red validation line).
     */
    private final JPanel panel = new JPanel(new java.awt.BorderLayout());
    /** The top-anchored BoxLayout content of the step (title → inputs → network row). */
    private final JPanel content = new JPanel();
    // The network selection (moved here from the node-configuration step — the
    // suggested name follows the choice live; SSOT: {@link Network}). Mocknet is
    // intentionally not offered (yet) — the network stays part of the suggested
    // name convention (mainnet / testnet).
    private final JRadioButton mainnetRadio = new JRadioButton("Mainnet (default)", true);
    private final JRadioButton testnetRadio = new JRadioButton("Testnet");
    private final JRadioButton suggestedRadio = new JRadioButton("Use suggested name", true);
    private final JRadioButton customRadio = new JRadioButton("Custom name");
    private final JTextField nameField = new JTextField(24);
    private final javax.swing.JEditorPane statusLabel = WizardTexts.info("");
    private final Supplier<java.util.Set<String>> takenNames;

    /** Live navigation context (bound by the controller; null in standalone use). */
    private WizardContext boundContext = null;
    private final List<Consumer<WizardContext>> changeListeners = new ArrayList<>();
    private boolean programmaticChange = false;

    public ProfileNameStep() {
        this(() -> new java.util.HashSet<>(NodeProfileRepository.discoverProfileNames()));
    }

    /** @param takenNames source of existing profile names (SSOT: repository discovery; injectable for tests). */
    public ProfileNameStep(java.util.function.Supplier<java.util.Set<String>> takenNames) {
        this.takenNames = takenNames;
        content.setLayout(new BoxLayout(content, BoxLayout.Y_AXIS));
        content.setOpaque(false);
        content.setBorder(BorderFactory.createEmptyBorder(4, 4, 4, 4));
        panel.setOpaque(false);

        // The step title (bold 1.2× keyword style, selectable like every other
        // display text of the wizard).
        javax.swing.JEditorPane title = WizardTexts.heading("Name the profile");
        title.setAlignmentX(0f);
        content.add(title);

        // A normal empty line between the title and the description.
        javax.swing.JEditorPane blankLine = WizardTexts.info("");
        blankLine.setAlignmentX(0f);
        content.add(blankLine);

        // One sentence per line (the full text stays readable without scrolling).
        javax.swing.JEditorPane info = WizardTexts.info(
                "The profile name identifies the node profile and its data directory.<br>"
                        + "The network is part of the suggested name (mainnet / testnet).<br>"
                        + "The suggested name follows the network / engine / port convention and is made unique automatically.<br>"
                        + "Choose a custom name when you want something different.");
        info.setAlignmentX(0f);
        content.add(info);
        content.add(Box.createVerticalStrut(6));

        ButtonGroup group = new ButtonGroup();
        group.add(suggestedRadio);
        group.add(customRadio);
        suggestedRadio.addActionListener(e -> {
            if (programmaticChange) {
                return;
            }
            suggestedRadio.setSelected(true);
            customRadio.setSelected(false);
            updateNameField();
            updateStatus();
            fireChange();
        });
        customRadio.addActionListener(e -> {
            if (programmaticChange) {
                return;
            }
            customRadio.setSelected(true);
            suggestedRadio.setSelected(false);
            updateNameField();
            nameField.requestFocusInWindow();
            updateStatus();
            fireChange();
        });
        // BoxLayout alignment: the Swing default (alignmentX = 0.5f) would center
        // each (width-varying) control in the panel — pin them to the left edge.
        suggestedRadio.setAlignmentX(0f);
        customRadio.setAlignmentX(0f);
        // The name field carries the app's standard input look (the same
        // styleInputComponent policy every other configuration field uses —
        // label font + the standard one-line control height) and is capped at
        // the wizard's content width (it must not overflow the dialog). It is the
        // name's single display: the live suggested name (read-only) while the
        // "suggested" option is selected, the user's editable text while "custom"
        // is selected.
        ConfigurationUtils.styleInputComponent(nameField);
        nameField.setAlignmentX(0f);
        nameField.setMaximumSize(new java.awt.Dimension(WizardTexts.STEP_WRAP_WIDTH,
                nameField.getPreferredSize().height));
        statusLabel.setAlignmentX(0f);
        nameField.setEnabled(false);
        content.add(suggestedRadio);
        content.add(customRadio);
        // Clear vertical breathing room between the choice radios and the
        // input (they almost touched before).
        content.add(Box.createVerticalStrut(12));
        content.add(nameField);
        content.add(statusLabel);

        // The network selection (the radios stacked one below the other — the
        // same pattern as the name-choice radios above — the suggested name
        // follows live), below the profile name. Mocknet is intentionally not
        // offered (yet).
        mainnetRadio.setAlignmentX(0f);
        testnetRadio.setAlignmentX(0f);
        ButtonGroup networkGroup = new ButtonGroup();
        networkGroup.add(mainnetRadio);
        networkGroup.add(testnetRadio);
        mainnetRadio.addActionListener(e -> onNetworkChanged());
        testnetRadio.addActionListener(e -> onNetworkChanged());
        content.add(Box.createVerticalStrut(10));
        content.add(mainnetRadio);
        content.add(testnetRadio);

        // Top-anchored: the dialog stretches the step's root panel to the full
        // available height — NORTH keeps the content at its preferred height
        // and leaves the extra space below (see the panel field's javadoc).
        panel.add(content, java.awt.BorderLayout.NORTH);

        nameField.getDocument().addDocumentListener(new DocumentListener() {
            @Override public void insertUpdate(DocumentEvent e) { if (!programmaticChange) { onChanged(); } }
            @Override public void removeUpdate(DocumentEvent e) { if (!programmaticChange) { onChanged(); } }
            @Override public void changedUpdate(DocumentEvent e) { if (!programmaticChange) { onChanged(); } }
        });
    }

    /** Live update: the validation feedback follows the keystrokes, the context the radio choice. */
    private void onChanged() {
        updateStatus();
        fireChange();
    }

    /**
     * Reflects the current choice in the name field — its single display of the
     * name. With the "suggested" option the field shows the live suggested name
     * (read-only: the user cannot edit it); with "custom" it is an editable
     * free-text input (the entered name, or blank). Programmatic — guarded so the
     * field's document listener does not fire a spurious change.
     */
    private void updateNameField() {
        programmaticChange = true;
        try {
            if (suggestedRadio.isSelected()) {
                nameField.setText(resolveSuggested(boundContext));
                nameField.setEnabled(false);
            } else {
                nameField.setEnabled(true);
            }
        } finally {
            programmaticChange = false;
        }
    }

    /** Mirrors the network radio choice into the context and updates the preview. */
    private void onNetworkChanged() {
        if (programmaticChange) {
            return;
        }
        // Only mainnet / testnet are offered (mocknet is not selectable for now).
        Network network = testnetRadio.isSelected() ? Network.TESTNET : Network.MAINNET;
        if (boundContext != null) {
            boundContext.setNetwork(network);
            for (Consumer<WizardContext> listener : changeListeners) {
                listener.accept(boundContext);
            }
        }
        updateNameField();
    }

    /** Selects the network radio of the given network (programmatic — no event loop). */
    private void selectNetwork(Network network) {
        programmaticChange = true;
        // Mocknet has no radio (not offered for now) — it maps to the mainnet
        // selection without changing the context.
        mainnetRadio.setSelected(network != Network.TESTNET);
        testnetRadio.setSelected(network == Network.TESTNET);
        programmaticChange = false;
    }

    /** Refreshes the (red) validation feedback line; blank while the name is valid. */
    private void updateStatus() {
        String error = validate(boundContext);
        if (error != null) {
            statusLabel.setForeground(Color.RED);
            statusLabel.setText(WizardTexts.wrap(WizardTexts.escape(error)));
        } else {
            Color c = UIManager.getColor("Label.foreground");
            statusLabel.setForeground(c != null ? c : Color.BLACK);
            statusLabel.setText(WizardTexts.wrap(""));
        }
    }

    /**
     * The suggested name for the given context: the SSOT base name (network /
     * engine — the ports no longer rename the profile) made unique against the
     * taken names. Never throws for transient (partially filled) contexts.
     */
    public String resolveSuggested(WizardContext context) {
        String networkName = context != null && context.getNetwork() != null
                ? context.getNetwork().getDisplayName()
                : Network.MAINNET.getDisplayName();
        String engineKey = context != null && context.getEngine() != null
                ? context.getEngine().getSettingsKey() : null;
        String base = ProfileNameSuggester.baseName(networkName, engineKey, false, 0);
        return ProfileNameSuggester.nextAvailableName(base, takenNames.get());
    }

    /** Resolves the profile name for the current UI state (custom or suggested). */
    public String resolveName(WizardContext context) {
        if (customRadio.isSelected()) {
            return nameField.getText().trim();
        }
        return resolveSuggested(context);
    }

    public boolean isCustomName() {
        return customRadio.isSelected();
    }

    public String getCustomName() {
        return nameField.getText().trim();
    }

    @Override
    public String getId() {
        return "profile-name";
    }

    @Override
    public String getTitle() {
        return "Profile name";
    }

    @Override
    public FontAwesome getHeaderIcon() {
        return FontAwesome.TAG;
    }

    @Override
    public JComponent getPanel() {
        return panel;
    }

    @Override
    public String validate(WizardContext context) {
        String name = resolveName(context);
        if (name.isEmpty()) {
            return "Profile name is required.";
        }
        if (!name.matches("[A-Za-z0-9._-]+")) {
            return "Invalid profile name '" + name + "' (allowed: letters, digits, '.', '_', '-').";
        }
        if (NodeProfileRepository.isReservedProfileName(name)) {
            return "Profile name '" + name + "' is reserved.";
        }
        if (takenNames.get().contains(name)) {
            return "A profile named '" + name + "' already exists.";
        }
        return null;
    }

    @Override
    public void onExit(WizardContext context) {
        context.setCustomName(customRadio.isSelected() ? nameField.getText().trim() : null);
        context.setName(resolveName(context));
    }

    @Override
    public void onEnter(WizardContext context) {
        if (context != null && context.getNetwork() != null) {
            selectNetwork(context.getNetwork());
        }
        updateNameField();
        updateStatus();
    }

    @Override
    public void bindContext(WizardContext context) {
        this.boundContext = context;
        if (context.getNetwork() != null) {
            selectNetwork(context.getNetwork());
        }
        updateNameField();
    }

    @Override
    public void addChangeListener(Consumer<WizardContext> listener) {
        changeListeners.add(listener);
    }

    /**
     * Mirrors the live name choice into the shared context and notifies the
     * controller (it re-resolves the suggested name and the dialog refreshes
     * the title bar).
     */
    private void fireChange() {
        if (boundContext == null) {
            return;
        }
        boundContext.setCustomName(customRadio.isSelected() ? nameField.getText().trim() : null);
        for (Consumer<WizardContext> listener : changeListeners) {
            listener.accept(boundContext);
        }
    }
}

