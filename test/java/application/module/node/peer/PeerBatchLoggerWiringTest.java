package application.module.node.peer;

import application.module.logging.context.NodeLoggingContext;
import application.module.logging.context.NodeLoggers;
import application.module.node.props.PropertyService;
import application.module.node.props.Props;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * P3-B2 (peer batch gate, plan §6/§7.5): the migrated peer-layer classes take
 * their loggers from the NODE's isolated LoggerContext — {@code isDebugEnabled()}
 * of a batch class reports that node context's level, and two nodes with the
 * same class get separate loggers bound to separate contexts. The no-context
 * {@code PeerImpl} overload falls back to the JVM-global context.
 */
@DisplayName("P3-B2 - peer batch logger wiring")
class PeerBatchLoggerWiringTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Signum — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The private {@code logger} field of a migrated peer class. */
    private static Logger loggerField(Object instance) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField("logger");
                f.setAccessible(true);
                return (Logger) f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no logger field on " + instance.getClass());
    }

    @Test
    @DisplayName("batch gate: PeerManager logger bound to the node context (isDebugEnabled per node level)")
    void peerManagerLoggerBoundToNodeContext() throws Exception {
        NodeLoggingContext debugNode = context("b2-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b2-warn.log4j2.properties", "WARN");
        try {
            PeerManager inDebug = new PeerManager(null, null, null, null, new NodeLoggers(debugNode.loggerContext()));
            PeerManager inWarn = new PeerManager(null, null, null, null, new NodeLoggers(warnNode.loggerContext()));

            Logger lDebug = loggerField(inDebug);
            Logger lWarn = loggerField(inWarn);
            assertNotSame(lDebug, lWarn,
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(lDebug.isDebugEnabled(), "the DEBUG node's PeerManager logger sees DEBUG");
            assertFalse(lWarn.isDebugEnabled(), "the WARN node's PeerManager logger does not");
            assertTrue(lWarn.isWarnEnabled());
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    @Test
    @DisplayName("GetMilestoneBlockIds + GetNextBlocks loggers bound to the node context")
    void requestHandlersBoundToNodeContext() throws Exception {
        NodeLoggingContext traceNode = context("b2-trace.log4j2.properties", "TRACE");
        try {
            NodeLoggers loggers = new NodeLoggers(traceNode.loggerContext());
            GetMilestoneBlockIds milestone = new GetMilestoneBlockIds(null, loggers);
            PropertyService propertyService = mock(PropertyService.class);
            when(propertyService.getInt(Props.P2P_MAX_BLOCKS)).thenReturn(720);
            GetNextBlocks nextBlocks = new GetNextBlocks(null, propertyService, loggers);
            assertTrue(loggerField(milestone).isTraceEnabled(),
                    "the node context's TRACE level must be visible on GetMilestoneBlockIds");
            assertTrue(loggerField(nextBlocks).isTraceEnabled(),
                    "the node context's TRACE level must be visible on GetNextBlocks");
        } finally {
            traceNode.stop();
        }
    }

    @Test
    @DisplayName("no-context PeerImpl overload falls back to the JVM-global context")
    void noContextFallbackIsGlobal() throws Exception {
        NodeLoggingContext node = context("b2-node.log4j2.properties", "ERROR");
        try {
            PeerImpl legacy = new PeerImpl("1.2.3.4:14015", null);
            Logger logger = loggerField(legacy);
            assertNotNull(logger, "the no-context PeerImpl still gets a usable (global) logger");
            org.apache.logging.log4j.core.LoggerContext ctx =
                    ((org.apache.logging.log4j.core.Logger) logger).getContext();
            assertNotSame(node.loggerContext(), ctx,
                    "a no-context PeerImpl must not bind to a node context");
        } finally {
            node.stop();
        }
    }
}