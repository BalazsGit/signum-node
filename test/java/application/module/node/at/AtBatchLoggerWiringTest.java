package application.module.node.at;

import application.module.logging.context.NodeLoggingContext;
import application.module.logging.context.NodeLoggers;
import application.module.node.db.store.ATStore;
import application.module.node.db.store.Dbs;
import application.module.node.db.sql.DbContext;
import application.module.node.props.PropertyService;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;

/**
 * P3-B4 (at batch gate, plan §6/§7.5): the migrated AT-layer classes take
 * their loggers from the NODE's isolated LoggerContext — {@code isDebugEnabled()}
 * of a batch class reports that node context's level, and two nodes with the
 * same class get separate loggers bound to separate contexts. The
 * {@code AtMachineProcessor} debug gate maps its "disabled" branch to a
 * guaranteed no-op logger (the SLF4J {@code NOPLogger} stand-in).
 */
@DisplayName("P3-B4 - at batch logger wiring")
class AtBatchLoggerWiringTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Node — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The private {@code logger} field of a migrated at class. */
    private static Logger loggerField(Object instance) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField("logger");
                f.setAccessible(true);
                return (Logger) f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no logger field on " + instance.getClass());
    }

    /** A context whose only live dependency is the given node loggers. */
    private static ATProcessingContext ctxWithLoggers(NodeLoggers loggers) {
        return new ATProcessingContext(
                null, null, null, null, null, null, null, null, null, null, null,
                new ATPendingState(), loggers);
    }

    @Test
    @DisplayName("batch gate: ATProcessorCache logger bound to the node context (isDebugEnabled per node level)")
    void atProcessorCacheBoundToNodeContext() throws Exception {
        NodeLoggingContext debugNode = context("b4-cache-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b4-cache-warn.log4j2.properties", "WARN");
        try {
            ATProcessorCache inDebug = new ATProcessorCache(
                    mock(PropertyService.class), mock(ATStore.class), mock(DbContext.class), mock(Dbs.class),
                    new NodeLoggers(debugNode.loggerContext()));
            ATProcessorCache inWarn = new ATProcessorCache(
                    mock(PropertyService.class), mock(ATStore.class), mock(DbContext.class), mock(Dbs.class),
                    new NodeLoggers(warnNode.loggerContext()));

            Logger lDebug = loggerField(inDebug);
            Logger lWarn = loggerField(inWarn);
            assertNotSame(lDebug, lWarn, "the same class in two nodes must be two distinct logger instances");
            assertTrue(lDebug.isDebugEnabled(), "the DEBUG node's ATProcessorCache logger sees DEBUG");
            assertFalse(lWarn.isDebugEnabled(), "the WARN node's ATProcessorCache logger does not");
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: AtMachineProcessor enabled logger bound to the node context")
    void atMachineProcessorEnabledBoundToNodeContext() throws Exception {
        NodeLoggingContext debugNode = context("b4-proc-debug.log4j2.properties", "DEBUG");
        try {
            NodeLoggers loggers = new NodeLoggers(debugNode.loggerContext());
            AtMachineProcessor processor =
                    new AtMachineProcessor(mock(AtMachineState.class), ctxWithLoggers(loggers), true);
            Logger logger = loggerField(processor);
            assertTrue(logger.isDebugEnabled(), "the enabled AtMachineProcessor logger must see the node's DEBUG");
            assertSame(debugNode.loggerContext(),
                    ((org.apache.logging.log4j.core.Logger) logger).getContext(),
                    "the enabled AtMachineProcessor logger must be bound to the node context");
        } finally {
            debugNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: AtMachineProcessor disabled branch is a guaranteed no-op logger")
    void atMachineProcessorDisabledIsNoop() throws Exception {
        NodeLoggingContext debugNode = context("b4-proc-off.log4j2.properties", "DEBUG");
        try {
            NodeLoggers loggers = new NodeLoggers(debugNode.loggerContext());
            // even on a DEBUG node, the disabled branch must be a no-op
            AtMachineProcessor processor =
                    new AtMachineProcessor(mock(AtMachineState.class), ctxWithLoggers(loggers), false);
            Logger logger = loggerField(processor);
            assertFalse(logger.isDebugEnabled(), "the disabled AtMachineProcessor logger must be a no-op");
        } finally {
            debugNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: NodeLoggers.noop() is a guaranteed no-op (SLF4J NOPLogger stand-in)")
    void noopLoggerIsOff() {
        Logger noop = NodeLoggers.global().noop();
        assertNotNull(noop, "noop() must return a usable logger");
        assertFalse(noop.isDebugEnabled(), "the no-op logger must have debug disabled");
        assertFalse(noop.isInfoEnabled(), "the no-op logger must have info disabled");
        assertFalse(noop.isErrorEnabled(), "the no-op logger must have error disabled");
        assertFalse(noop.isTraceEnabled(), "the no-op logger must have trace disabled");
    }
}
