package application.module.node.db.sql;

import application.module.logging.context.NodeLoggingContext;
import application.module.logging.context.NodeLoggers;
import application.module.node.db.store.DerivedTableManager;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * P3-B1 (db batch gate, plan §6/§7.5): the migrated db-layer classes take
 * their loggers from the NODE's isolated LoggerContext — {@code isDebugEnabled()}
 * of a batch class reports that node context's level, and two nodes with the
 * same class get separate loggers bound to separate contexts. Deprecated
 * no-context overloads fall back to the JVM-global context.
 */
@DisplayName("P3-B1 - db batch logger wiring")
class DbBatchLoggerWiringTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Signum — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The private/protected {@code logger} field of a migrated db class. */
    private static Logger loggerField(Object instance) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField("logger");
                f.setAccessible(true);
                return (Logger) f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no logger field on " + instance.getClass());
    }

    @Test
    @DisplayName("batch gate: SqlBlockDb logger bound to the node context (isDebugEnabled per node level)")
    void sqlBlockDbLoggerBoundToNodeContext() throws Exception {
        NodeLoggingContext debugNode = context("b1-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b1-warn.log4j2.properties", "WARN");
        try {
            SqlBlockDb inDebug = new SqlBlockDb(new DbContext(new NodeLoggers(debugNode.loggerContext())));
            SqlBlockDb inWarn = new SqlBlockDb(new DbContext(new NodeLoggers(warnNode.loggerContext())));

            Logger lDebug = loggerField(inDebug);
            Logger lWarn = loggerField(inWarn);
            assertNotSame(lDebug, lWarn,
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(lDebug.isDebugEnabled(), "the DEBUG node's SqlBlockDb logger sees DEBUG");
            assertFalse(lWarn.isDebugEnabled(), "the WARN node's SqlBlockDb logger does not");
            assertTrue(lWarn.isWarnEnabled());
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    @Test
    @DisplayName("DerivedTableManager logger bound to the node context")
    void derivedTableManagerLoggerBoundToNodeContext() throws Exception {
        NodeLoggingContext traceNode = context("b1-trace.log4j2.properties", "TRACE");
        try {
            DerivedTableManager manager = new DerivedTableManager(new NodeLoggers(traceNode.loggerContext()));
            assertTrue(loggerField(manager).isTraceEnabled(),
                    "the node context's TRACE level must be visible on the manager's logger");
        } finally {
            traceNode.stop();
        }
    }

    @Test
    @DisplayName("deprecated no-context overloads fall back to the JVM-global context")
    void noContextFallbackIsGlobal() throws Exception {
        NodeLoggingContext node = context("b1-node.log4j2.properties", "ERROR");
        try {
            SqlBlockDb legacy = new SqlBlockDb();
            Logger logger = loggerField(legacy);
            assertNotNull(logger, "the deprecated overload still gets a usable (global) logger");
            // The global context must NOT be the node's isolated context.
            org.apache.logging.log4j.core.LoggerContext ctx =
                    ((org.apache.logging.log4j.core.Logger) logger).getContext();
            assertNotSame(node.loggerContext(), ctx,
                    "a no-context SqlBlockDb must not bind to a node context");

            assertNotNull(new DbContext().loggers(),
                    "the no-arg DbContext falls back to the global loggers");
        } finally {
            node.stop();
        }
    }
}