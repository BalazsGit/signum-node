package application.module.node.services.impl;

import application.module.logging.context.NodeLoggingContext;
import application.module.logging.context.NodeLoggers;
import application.module.node.statistics.StatisticsManagerImpl;
import application.module.node.transactionduplicates.TransactionDuplicatesCheckerImpl;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * P3-B5 (services+stat batch gate, plan §6/§7.5): the migrated service/stat
 * classes take their loggers from the NODE's isolated LoggerContext —
 * {@code isDebugEnabled()} of a batch class reports that node context's level,
 * and two nodes with the same class get separate loggers bound to separate
 * contexts. The multi-site {@code TransactionDuplicatesCheckerImpl} keeps a
 * no-context overload that falls back to the JVM-global context (its remaining
 * call sites in {@code BlockchainProcessorImpl} / {@code UnconfirmedTransactionStoreImpl}
 * are handled in their own batches).
 */
@DisplayName("P3-B5 - services+stat batch logger wiring")
class ServicesBatchLoggerWiringTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Node — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The private {@code logger} field of a migrated services/stat class. */
    private static Logger loggerField(Object instance) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField("logger");
                f.setAccessible(true);
                return (Logger) f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no logger field on " + instance.getClass());
    }

    @Test
    @DisplayName("batch gate: BlockServiceImpl + StatisticsManagerImpl loggers bound to the node context")
    void servicesBoundToNodeContext() throws Exception {
        NodeLoggingContext debugNode = context("b5-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b5-warn.log4j2.properties", "WARN");
        try {
            BlockServiceImpl blockInDebug = new BlockServiceImpl(
                    null, null, null, null, null, null, null, null,
                    new NodeLoggers(debugNode.loggerContext()));
            BlockServiceImpl blockInWarn = new BlockServiceImpl(
                    null, null, null, null, null, null, null, null,
                    new NodeLoggers(warnNode.loggerContext()));
            StatisticsManagerImpl statsInDebug =
                    new StatisticsManagerImpl(null, new NodeLoggers(debugNode.loggerContext()));

            Logger blockDebug = loggerField(blockInDebug);
            Logger blockWarn = loggerField(blockInWarn);
            assertNotSame(blockDebug, blockWarn,
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(blockDebug.isDebugEnabled(), "the DEBUG node's BlockServiceImpl logger sees DEBUG");
            assertFalse(blockWarn.isDebugEnabled(), "the WARN node's BlockServiceImpl logger does not");
            assertTrue(loggerField(statsInDebug).isDebugEnabled(),
                    "the DEBUG node's StatisticsManagerImpl logger sees DEBUG");
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: TransactionDuplicatesCheckerImpl (explicit NodeLoggers) bound to the node context")
    void duplicatesCheckerBoundToNodeContext() throws Exception {
        NodeLoggingContext traceNode = context("b5-trace.log4j2.properties", "TRACE");
        try {
            NodeLoggers loggers = new NodeLoggers(traceNode.loggerContext());
            TransactionDuplicatesCheckerImpl checker = new TransactionDuplicatesCheckerImpl(loggers);
            Logger logger = loggerField(checker);
            assertTrue(logger.isTraceEnabled(), "the node context's TRACE level must be visible on the checker");
            assertSame(traceNode.loggerContext(),
                    ((org.apache.logging.log4j.core.Logger) logger).getContext(),
                    "the checker logger must be bound to the node context");
        } finally {
            traceNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: no-context TransactionDuplicatesCheckerImpl overload falls back to the JVM-global context")
    void noContextFallbackIsGlobal() throws Exception {
        NodeLoggingContext node = context("b5-node.log4j2.properties", "ERROR");
        try {
            TransactionDuplicatesCheckerImpl legacy = new TransactionDuplicatesCheckerImpl();
            Logger logger = loggerField(legacy);
            assertNotNull(logger, "the no-context checker still gets a usable (global) logger");
            org.apache.logging.log4j.core.LoggerContext ctx =
                    ((org.apache.logging.log4j.core.Logger) logger).getContext();
            assertNotSame(node.loggerContext(), ctx,
                    "a no-context checker must not bind to a node context");
        } finally {
            node.stop();
        }
    }
}
