package application.module.node;

import application.module.logging.context.NodeLoggingContext;
import application.module.logging.context.NodeLoggers;
import application.module.node.props.PropertyService;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;

/**
 * P3-B6.5 (static-utility batch, plan §7.5 / §15): {@link OCLPoC} is no longer
 * a static utility — it is a per-node instance that owns its OpenCL state and
 * takes its logger from the NODE's isolated
 * {@link org.apache.logging.log4j.core.LoggerContext} (plan A.1/3, §7.1).
 * <p>
 * This test verifies the isolation invariants WITHOUT touching real
 * GPU/OpenCL resources (no {@code configure()} call): two nodes that use the
 * same {@code OCLPoC} class must get (a) distinct instances and (b) distinct
 * loggers bound to distinct contexts. That proves the previously-shared static
 * state / JVM-global SLF4J logger is gone.
 * </p>
 *
 * @since 4.0
 */
@DisplayName("P3-B6.5 - OCLPoC per-node instance + logger isolation")
class OclPoCNodeIsolationTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Signum — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The named field of a component, walking the superclass chain. */
    private static Object field(Object instance, String name) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField(name);
                f.setAccessible(true);
                return f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no field " + name + " on " + instance.getClass());
    }

    private static Logger loggerOf(Object instance) throws Exception {
        return (Logger) field(instance, "logger");
    }

    private static org.apache.logging.log4j.core.LoggerContext ctxOf(Logger logger) {
        return ((org.apache.logging.log4j.core.Logger) logger).getContext();
    }

    @Test
    @DisplayName("two nodes get distinct OCLPoC instances AND distinct loggers bound to distinct contexts")
    void oclPoCIsolatedPerNode() throws Exception {
        NodeLoggingContext debugNode = context("b65-ocl-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b65-ocl-warn.log4j2.properties", "WARN");
        try {
            PropertyService propertyService = mock(PropertyService.class);
            OCLPoC oclInDebug = new OCLPoC(propertyService, new NodeLoggers(debugNode.loggerContext()));
            OCLPoC oclInWarn = new OCLPoC(propertyService, new NodeLoggers(warnNode.loggerContext()));

            assertNotSame(oclInDebug, oclInWarn,
                    "each node must own its OCLPoC instance (no shared static singleton)");

            assertNotSame(loggerOf(oclInDebug), loggerOf(oclInWarn),
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(loggerOf(oclInDebug).isDebugEnabled(),
                    "the DEBUG node's OCLPoC logger sees DEBUG");
            assertFalse(loggerOf(oclInWarn).isDebugEnabled(),
                    "the WARN node's OCLPoC logger does not");
            assertSame(debugNode.loggerContext(), ctxOf(loggerOf(oclInDebug)),
                    "the OCLPoC logger must be bound to the node's context");
            assertSame(warnNode.loggerContext(), ctxOf(loggerOf(oclInWarn)),
                    "the OCLPoC logger must be bound to the node's context");
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }
}