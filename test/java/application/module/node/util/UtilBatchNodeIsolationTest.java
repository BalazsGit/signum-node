package application.module.node.util;

import application.module.logging.context.NodeLoggingContext;
import application.module.logging.context.NodeLoggers;
import application.module.node.Blockchain;
import application.module.node.fluxcapacitor.FluxCapacitor;
import application.module.node.props.PropertyService;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;

/**
 * P3-B7 (util batch, plan §15): {@link ThreadPool} and {@link DownloadCacheImpl}
 * take their logger from the NODE's isolated
 * {@link org.apache.logging.log4j.core.LoggerContext} (via
 * {@link NodeLoggers#forClass}), so each node's thread pool / download cache log
 * to their own node console instead of the JVM-global context.
 * <p>
 * Verifies, without real GPU / network / cache work, that two nodes using the
 * same classes get (a) distinct instances and (b) distinct loggers bound to
 * distinct contexts — the same isolation invariant proven for {@code OCLPoC}
 * in {@code OclPoCNodeIsolationTest}.
 * </p>
 *
 * @since 4.0
 */
@DisplayName("P3-B7 - util (ThreadPool + DownloadCacheImpl) logger isolation")
class UtilBatchNodeIsolationTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Node — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The named field of a component, walking the superclass chain. */
    private static Object field(Object instance, String name) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField(name);
                f.setAccessible(true);
                return f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no field " + name + " on " + instance.getClass());
    }

    private static Logger loggerOf(Object instance) throws Exception {
        return (Logger) field(instance, "logger");
    }

    private static org.apache.logging.log4j.core.LoggerContext ctxOf(Logger logger) {
        return ((org.apache.logging.log4j.core.Logger) logger).getContext();
    }

    @Test
    @DisplayName("two nodes get distinct ThreadPool instances AND distinct loggers bound to distinct contexts")
    void threadPoolIsolatedPerNode() throws Exception {
        NodeLoggingContext debugNode = context("b7-pool-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b7-pool-warn.log4j2.properties", "WARN");
        try {
            ThreadPool poolInDebug = new ThreadPool(mock(PropertyService.class),
                    new NodeLoggers(debugNode.loggerContext()));
            ThreadPool poolInWarn = new ThreadPool(mock(PropertyService.class),
                    new NodeLoggers(warnNode.loggerContext()));

            assertNotSame(poolInDebug, poolInWarn,
                    "each node must own its ThreadPool instance");
            assertNotSame(loggerOf(poolInDebug), loggerOf(poolInWarn),
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(loggerOf(poolInDebug).isDebugEnabled(),
                    "the DEBUG node's ThreadPool logger sees DEBUG");
            assertFalse(loggerOf(poolInWarn).isDebugEnabled(),
                    "the WARN node's ThreadPool logger does not");
            assertSame(debugNode.loggerContext(), ctxOf(loggerOf(poolInDebug)),
                    "the ThreadPool logger must be bound to the node's context");
            assertSame(warnNode.loggerContext(), ctxOf(loggerOf(poolInWarn)),
                    "the ThreadPool logger must be bound to the node's context");
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    @Test
    @DisplayName("two nodes get distinct DownloadCacheImpl instances AND distinct loggers bound to distinct contexts")
    void downloadCacheIsolatedPerNode() throws Exception {
        NodeLoggingContext debugNode = context("b7-cache-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b7-cache-warn.log4j2.properties", "WARN");
        try {
            DownloadCacheImpl cacheInDebug = new DownloadCacheImpl(
                    mock(PropertyService.class), mock(FluxCapacitor.class), mock(Blockchain.class),
                    new NodeLoggers(debugNode.loggerContext()));
            DownloadCacheImpl cacheInWarn = new DownloadCacheImpl(
                    mock(PropertyService.class), mock(FluxCapacitor.class), mock(Blockchain.class),
                    new NodeLoggers(warnNode.loggerContext()));

            assertNotSame(cacheInDebug, cacheInWarn,
                    "each node must own its DownloadCacheImpl instance");
            assertNotSame(loggerOf(cacheInDebug), loggerOf(cacheInWarn),
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(loggerOf(cacheInDebug).isDebugEnabled(),
                    "the DEBUG node's DownloadCacheImpl logger sees DEBUG");
            assertFalse(loggerOf(cacheInWarn).isDebugEnabled(),
                    "the WARN node's DownloadCacheImpl logger does not");
            assertSame(debugNode.loggerContext(), ctxOf(loggerOf(cacheInDebug)),
                    "the DownloadCacheImpl logger must be bound to the node's context");
            assertSame(warnNode.loggerContext(), ctxOf(loggerOf(cacheInWarn)),
                    "the DownloadCacheImpl logger must be bound to the node's context");
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }
}