/**
 * P3-B6 (top-level + unconfirmedtransactions batch gate, plan §6/§7.5): the
 * migrated top-level node classes take their loggers from the NODE's isolated
 * LoggerContext — {@code isDebugEnabled()} reports that node context's level and
 * two nodes with the same class get separate loggers bound to separate contexts.
 * <p>
 * Crucially, {@code UnconfirmedTransactionStoreImpl} now wires its
 * {@code TransactionDuplicatesCheckerImpl} to the node's loggers, closing the
 * no-arg global-fallback gap found by the audit (the checker that used to log to
 * the JVM-global context even when running inside a live node).
 * </p>
 */
@DisplayName("P3-B6 - top-level + unconfirmedtransactions batch logger wiring")
class TopLevelBatchLoggerWiringTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Node — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    /** The named field of a component, walking the superclass chain. */
    private static Object field(Object instance, String name) throws Exception {
        Class<?> c = instance.getClass();
        while (c != null) {
            try {
                Field f = c.getDeclaredField(name);
                f.setAccessible(true);
                return f.get(instance);
            } catch (NoSuchFieldException e) {
                c = c.getSuperclass();
            }
        }
        throw new AssertionError("no field " + name + " on " + instance.getClass());
    }

    private static Logger loggerOf(Object instance) throws Exception {
        return (Logger) field(instance, "logger");
    }

    private static org.apache.logging.log4j.core.LoggerContext ctxOf(Logger logger) {
        return ((org.apache.logging.log4j.core.Logger) logger).getContext();
    }

    @Test
    @DisplayName("batch gate: top-level singletons bound to the node context (two nodes isolated)")
    void topLevelBoundToNodeContext() throws Exception {
        NodeLoggingContext debugNode = context("b6-debug.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("b6-warn.log4j2.properties", "WARN");
        try {
            EconomicClustering ecInDebug = new EconomicClustering(null, null,
                    new NodeLoggers(debugNode.loggerContext()));
            EconomicClustering ecInWarn = new EconomicClustering(null, null,
                    new NodeLoggers(warnNode.loggerContext()));
            GeneratorImpl genInDebug = new GeneratorImpl(null, null, null, null, null,
                    new NodeLoggers(debugNode.loggerContext()));

            assertNotSame(loggerOf(ecInDebug), loggerOf(ecInWarn),
                    "the same class in two nodes must be two distinct logger instances");
            assertTrue(loggerOf(ecInDebug).isDebugEnabled(),
                    "the DEBUG node's EconomicClustering logger sees DEBUG");
            assertFalse(loggerOf(ecInWarn).isDebugEnabled(),
                    "the WARN node's EconomicClustering logger does not");
            assertSame(debugNode.loggerContext(), ctxOf(loggerOf(genInDebug)),
                    "the GeneratorImpl logger must be bound to the node context");
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: TransactionProcessorImpl logger bound to the node context")
    void transactionProcessorBoundToNodeContext() throws Exception {
        NodeLoggingContext traceNode = context("b6-tpi.log4j2.properties", "TRACE");
        try {
            PropertyService propertyService = mock(PropertyService.class);
            Stores stores = mock(Stores.class);
            when(stores.getUnconfirmedTransactionStore()).thenReturn(mock(UnconfirmedTransactionStore.class));
            TransactionProcessorImpl tpi = new TransactionProcessorImpl(
                    propertyService, null, null, stores, null, null, null, null, null,
                    mock(ThreadPool.class),
                    new NodeLoggers(traceNode.loggerContext()));
            Logger logger = loggerOf(tpi);
            assertTrue(logger.isTraceEnabled(), "the TRACE node's TransactionProcessorImpl logger sees TRACE");
            assertSame(traceNode.loggerContext(), ctxOf(logger),
                    "the TransactionProcessorImpl logger must be bound to the node context");
        } finally {
            traceNode.stop();
        }
    }

    @Test
    @DisplayName("batch gate: UnconfirmedTransactionStoreImpl wires its TransactionDuplicatesCheckerImpl to the node context (audit gap)")
    void unconfirmedStoreCheckerBoundToNodeContext() throws Exception {
        NodeLoggingContext traceNode = context("b6-uts.log4j2.properties", "TRACE");
        try {
            PropertyService propertyService = mock(PropertyService.class);
            UnconfirmedTransactionStoreImpl store = new UnconfirmedTransactionStoreImpl(
                    null, propertyService, null, null, null,
                    new NodeLoggers(traceNode.loggerContext()));

            assertSame(traceNode.loggerContext(), ctxOf(loggerOf(store)),
                    "the UnconfirmedTransactionStoreImpl logger must be bound to the node context");

            // the audit gap: the store's TransactionDuplicatesCheckerImpl must inherit the node
            // context (it used to fall back to the JVM-global context via the no-arg constructor)
            TransactionDuplicatesCheckerImpl checker =
                    (TransactionDuplicatesCheckerImpl) field(store, "transactionDuplicatesChecker");
            Logger checkerLogger = loggerOf(checker);
            assertSame(traceNode.loggerContext(), ctxOf(checkerLogger),
                    "the store's TransactionDuplicatesCheckerImpl logger must be bound to the node context, not global");
        } finally {
            traceNode.stop();
        }
    }
}