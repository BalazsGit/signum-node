package application.module.logging.appender;

import application.module.logging.context.NodeLoggingContext;
import application.utils.logging.ProfileLogger;
import application.utils.logging.SystemLogger;
import application.utils.logging.event.LogEvent;
import application.utils.logging.event.LogFilter;
import application.utils.logging.event.LogLevel;
import application.utils.logging.event.LogSubscriber;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * P2.2: {@link ProfileConsoleAppender} / {@link SystemConsoleAppender} — the
 * programmatic GUI-bridge appenders (plan §7.3): context &rarr; bus delivery,
 * context-only level gating, and the P0 re-attach contract (reconfigure drops
 * the reference without stopping the appender; re-attach is idempotent).
 */
@DisplayName("P2.2 - Console bus appenders")
class ConsoleBusAppenderTest {

    @TempDir
    Path tempDir;

    @BeforeEach
    void setUp() throws Exception {
        SystemLogger.resetInstance();
    }

    @AfterAll
    static void tearDown() {
        SystemLogger.resetInstance();
    }

    /** Captures every bus event for assertions. */
    private static final class Recorder implements LogSubscriber {
        final List<LogEvent> events = new CopyOnWriteArrayList<>();
        @Override
        public void onLogEvent(final LogEvent event) {
            events.add(event);
        }
        @Override
        public LogFilter getFilter() {
            return null;
        }
    }

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Signum — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    @Test
    @DisplayName("node event reaches the ProfileLogger bus once, formatted (BriefLogFormatter-style)")
    void profileDelivery() throws Exception {
        NodeLoggingContext nlc = context("ca1.log4j2.properties", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "ca-profile");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            Logger engine = nlc.loggerContext().getLogger("com.example.engine");
            engine.info("hello {}", "world");

            assertEquals(1, recorder.events.size(), "exactly one bus event");
            LogEvent e = recorder.events.get(0);
            assertEquals(LogLevel.INFO, e.getLevel());
            assertTrue(e.getMessage().startsWith("[INFO] "), "BriefLogFormatter-style header");
            assertTrue(e.getMessage().contains("[") && e.getMessage().contains("] "),
                    "thread segment present: " + e.getMessage());
            assertTrue(e.getMessage().endsWith("com.example.engine - hello world"),
                    "logger name + formatted message: " + e.getMessage());
        } finally {
            nlc.stop();
            bus.close();
        }
    }

    @Test
    @DisplayName("the context configuration is the sole level gate (no second bus gate)")
    void levelGate() throws Exception {
        NodeLoggingContext nlc = context("ca2.log4j2.properties", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "ca-gate");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            Logger logger = nlc.loggerContext().getLogger("com.example.Gate");
            logger.debug("too quiet");   // below the INFO root: never reaches the appender
            logger.warn("loud enough");
            assertEquals(1, recorder.events.size(), "DEBUG suppressed by the context, WARN delivered");
            assertEquals(LogLevel.WARN, recorder.events.get(0).getLevel());
        } finally {
            nlc.stop();
            bus.close();
        }
    }

    @Test
    @DisplayName("the context is the sole gate even below the bus default (DEBUG reaches the bus; TRACE is suppressed at the source)")
    void contextIsSoleGateBelowBusDefault() throws Exception {
        // Context root = DEBUG. The bus is intentionally left at its DEFAULT
        // (INFO) minLevel: with the second gate removed from the bridge, the
        // native context (DEBUG) is the ONLY gate — so DEBUG must reach the bus,
        // while TRACE is suppressed at the source by the context.
        NodeLoggingContext nlc = context("ca3.log4j2.properties", "DEBUG");
        ProfileLogger bus = new ProfileLogger("node", "ca-sole-gate");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            Logger logger = nlc.loggerContext().getLogger("com.example.SoleGate");
            logger.debug("debug passes the native gate");   // root=DEBUG → emitted; the bus must not re-filter
            logger.trace("trace suppressed at the source");  // below the DEBUG root → never emitted by the context

            assertEquals(1, recorder.events.size(),
                    "DEBUG delivered by the bus, TRACE suppressed by the (native) context — no second gate");
            assertEquals(LogLevel.DEBUG, recorder.events.get(0).getLevel());
        } finally {
            nlc.stop();
            bus.close();
        }
    }

    @Test
    @DisplayName("a throwable in the message is appended to the bus event")
    void throwableForwarding() throws Exception {
        NodeLoggingContext nlc = context("ca3.log4j2.properties", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "ca-throw");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        try {
            new ProfileConsoleAppender(bus).attach(nlc.loggerContext());
            nlc.loggerContext().getLogger("com.example.Throw").error("boom", new IllegalStateException("inner"));
            assertEquals(1, recorder.events.size());
            assertTrue(recorder.events.get(0).getMessage().contains("com.example.Throw - boom"));
            assertTrue(recorder.events.get(0).getMessage().contains("IllegalStateException: inner"));
        } finally {
            nlc.stop();
            bus.close();
        }
    }

    @Test
    @DisplayName("reconfigure drops the appender (P0) — re-attach is idempotent, no double delivery")
    void reconfigureReattach() throws Exception {
        NodeLoggingContext nlc = context("ca4.log4j2.properties", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "ca-reattach");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            // attaching twice without a reconfigure: still no duplicate
            appender.attach(nlc.loggerContext());
            Logger logger = nlc.loggerContext().getLogger("com.example.Re");
            logger.info("first");
            assertEquals(1, recorder.events.size(), "double attach == one delivery");

            nlc.reconfigure(); // the new configuration no longer references the appender
            appender.attach(nlc.loggerContext()); // re-attach the SAME running instance
            logger.info("second");
            assertEquals(2, recorder.events.size(), "after reconfigure+reattach: exactly one per event");
        } finally {
            nlc.stop();
            bus.close();
        }
    }

    @Test
    @DisplayName("stop -> start (node restart) keeps the appender working, no duplicates (Q6/T16 core)")
    void restartCycle() throws Exception {
        NodeLoggingContext nlc = context("ca5.log4j2.properties", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "ca-restart");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            Logger logger = nlc.loggerContext().getLogger("com.example.Restart");
            logger.info("before");
            nlc.stop();
            nlc.start();
            appender.attach(nlc.loggerContext()); // idempotent after a plain (re)start
            logger.info("after");
            assertEquals(2, recorder.events.size(), "one event before, one after — no duplicates");
        } finally {
            nlc.stop();
            bus.close();
        }
    }

    @Test
    @DisplayName("SystemConsoleAppender forwards global-context events to the SystemLogger")
    void systemDelivery() throws Exception {
        NodeLoggingContext globalLike = context("ca6.log4j2.properties", "ERROR");
        SystemLogger systemLogger = SystemLogger.getInstance();
        Recorder recorder = new Recorder();
        systemLogger.addSubscriber(recorder);
        SystemConsoleAppender appender = new SystemConsoleAppender(systemLogger);
        try {
            appender.attach(globalLike.loggerContext());
            globalLike.loggerContext().getLogger("com.example.Global").error("system event");
            assertEquals(1, recorder.events.size());
            assertEquals(LogLevel.ERROR, recorder.events.get(0).getLevel());
            assertTrue(recorder.events.get(0).getMessage().endsWith("com.example.Global - system event"));
        } finally {
            globalLike.stop();
        }
    }

    @Test
    @DisplayName("Log4j2 -> bus level mapping (FATAL collapses to ERROR)")
    void levelMapping() {
        assertEquals(LogLevel.TRACE, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.TRACE));
        assertEquals(LogLevel.DEBUG, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.DEBUG));
        assertEquals(LogLevel.INFO, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.INFO));
        assertEquals(LogLevel.WARN, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.WARN));
        assertEquals(LogLevel.ERROR, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.ERROR));
        assertEquals(LogLevel.ERROR, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.FATAL));
        assertEquals(LogLevel.OFF, ConsoleBusAppender.toBusLevel(org.apache.logging.log4j.Level.OFF));
    }
}