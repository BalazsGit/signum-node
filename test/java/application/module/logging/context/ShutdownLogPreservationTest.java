package application.module.logging.context;

import application.module.logging.appender.ProfileConsoleAppender;
import application.utils.logging.ProfileLogger;
import application.utils.logging.event.LogEvent;
import application.utils.logging.event.LogFilter;
import application.utils.logging.event.LogSubscriber;
import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicReference;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * T18 (plan §13 / §14.4 A6): shutdown-log preservation.
 * <p>
 * The {@code Signum.doShutdown()} ordering fix (audit P1.2) stops the isolated
 * node {@link NodeLoggingContext} LAST — in the {@code finally} block, after
 * every motor has quiesced — so the node's final business log (e.g.
 * {@code "Node profile '<x>' stopped."}) is written by the context's appenders
 * BEFORE they close. A log that arrives AFTER the context is stopped (a
 * "late-arriving" executor task) is dropped: the context (and its appenders)
 * are already shut down.
 * <p>
 * This test pins the context-level contract that makes that ordering correct,
 * without requiring a fully started node (DB + motor threads):
 * <ol>
 *   <li>a log emitted while the context is live is delivered to the Node
 *       Console bus ({@link ProfileConsoleAppender} &rarr; {@link ProfileLogger});</li>
 *   <li>after {@link NodeLoggingContext#stop()} the same logger's events are
 *       dropped (the appender is stopped) — so no shutdown log is lost AND no
 *       post-stop log is delivered.</li>
 * </ol>
 */
@DisplayName("T18 - shutdown-log preservation (last business log survives, post-stop log dropped)")
class ShutdownLogPreservationTest {

    @TempDir
    Path tempDir;

    /** Builds a started node context from a minimal generated config (root level only). */
    private NodeLoggingContext context(String profile, String rootLevel) throws Exception {
        Path p = tempDir.resolve(profile + ".log4j2.properties");
        Files.writeString(p, "# GENERATED by Node — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(profile, p.toUri()).start();
    }

    @Test
    @DisplayName("a log before stop() reaches the Node Console bus; a log after stop() is dropped")
    void lastBusinessLogPreserved_postStopLogDropped() throws Exception {
        NodeLoggingContext nlc = context("t18-sequential", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "t18-sequential");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            Logger engine = nlc.loggerContext().getLogger("application.module.node.t18.Engine");

            String last = "T18_LAST_" + System.nanoTime();
            String late = "T18_LATE_" + System.nanoTime();

            // 1) the LAST business log — the context (and its appenders) are still live
            engine.info(last);
            awaitEvent(recorder, last);

            // 2) stop the isolated context LAST (the doShutdown() finally ordering, audit P1.2)
            nlc.stop();

            // 3) the last business log survived the stop (appenders flushed before closing)
            assertTrue(contains(recorder, last),
                    "the last business log must be delivered to the Node Console before the context stops");

            // 4) a LATE log after the stop is dropped (context + appenders are already closed)
            engine.info(late);
            settle();
            assertFalse(contains(recorder, late),
                    "a log emitted after the context stop() must be dropped, not delivered to the console bus");
        } finally {
            stopIfStarted(nlc);
            bus.close();
        }
    }

    @Test
    @DisplayName("a late-arriving executor task that logs after stop() is dropped (P1.2 follow-up case)")
    void lateExecutorTaskLogDropped() throws Exception {
        NodeLoggingContext nlc = context("t18-late-task", "INFO");
        ProfileLogger bus = new ProfileLogger("node", "t18-late-task");
        bus.setForwardToSystem(false);
        Recorder recorder = new Recorder();
        bus.addSubscriber(recorder);
        ProfileConsoleAppender appender = new ProfileConsoleAppender(bus);
        try {
            appender.attach(nlc.loggerContext());
            Logger engine = nlc.loggerContext().getLogger("application.module.node.t18.Task");

            String last = "T18_LAST_" + System.nanoTime();
            String late = "T18_LATE_TASK_" + System.nanoTime();
            CountDownLatch taskReleased = new CountDownLatch(1);
            AtomicReference<Throwable> taskError = new AtomicReference<>();

            // a background "executor task" that logs once it is released (i.e. strictly AFTER the stop)
            Thread task = new Thread(() -> {
                try {
                    taskReleased.await(5, TimeUnit.SECONDS);
                    engine.info(late);
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (Throwable t) {
                    taskError.set(t);
                }
            }, "t18-late-task");
            task.start();
            try {
                engine.info(last);
                awaitEvent(recorder, last);

                // the context stops; only THEN is the late task allowed to log
                nlc.stop();
                taskReleased.countDown();
                task.join(TimeUnit.SECONDS.toMillis(5));
            } finally {
                if (task.isAlive()) {
                    task.join(TimeUnit.SECONDS.toMillis(1));
                }
            }

            assertNull(taskError.get(),
                    "the late task must not throw when logging into a stopped context");
            assertTrue(contains(recorder, last), "the last business log must survive the stop");
            assertFalse(contains(recorder, late),
                    "a late executor task logging after the context stop() must be dropped");
        } finally {
            stopIfStarted(nlc);
            bus.close();
        }
    }

    // --- helpers ---------------------------------------------------------

    private static boolean contains(Recorder r, String needle) {
        return r.events.stream().anyMatch(e -> e.getMessage() != null && e.getMessage().contains(needle));
    }

    /** Bounded wait for a (synchronous) bus delivery — insurance against any batching. */
    private static void awaitEvent(Recorder r, String needle) throws InterruptedException {
        long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(3);
        while (!contains(r, needle) && System.nanoTime() < deadline) {
            Thread.sleep(5);
        }
    }

    private static void settle() throws InterruptedException {
        Thread.sleep(100);
    }

    private static void stopIfStarted(NodeLoggingContext nlc) {
        try {
            if (nlc.isStarted()) {
                nlc.stop();
            }
        } catch (Exception ignored) {
            // best-effort cleanup
        }
    }

    /** Captures every bus event for assertions. */
    private static final class Recorder implements LogSubscriber {
        final List<LogEvent> events = new CopyOnWriteArrayList<>();

        @Override
        public void onLogEvent(final LogEvent event) {
            events.add(event);
        }

        @Override
        public LogFilter getFilter() {
            return null;
        }
    }
}