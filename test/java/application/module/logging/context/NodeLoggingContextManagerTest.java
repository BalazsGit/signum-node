package application.module.logging.context;

import org.apache.logging.log4j.core.LoggerContext;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * P1.3: {@link NodeLoggingContext} / {@link NodeLoggingContextManager} —
 * direct (D7) context ownership, the deterministic context name, and the
 * stop/start/reconfigure lifecycle through the P1 API (P0 spikes Q2b/Q6).
 */
@DisplayName("P1.3 - NodeLoggingContext + Manager")
class NodeLoggingContextManagerTest {

    @TempDir
    Path tempDir;

    /** Writes a minimal generated config ({@code rootLogger.level = <level>}) and returns its path. */
    private Path minimalConfig(String file, String level) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Signum — do not edit\n"
                + "status = ERROR\n"
                + "configWatch = false\n"
                + "rootLogger.level = " + level + "\n");
        return p;
    }

    @Test
    @DisplayName("context name is deterministic: signum-node-<sanitized profile>")
    void contextNameIsSanitized() {
        assertEquals("signum-node-mainnet", NodeLoggingContext.contextNameFor("mainnet"));
        assertEquals("signum-node-main_net_x", NodeLoggingContext.contextNameFor("main net!x"));
        assertEquals("signum-node-a.b_c-d", NodeLoggingContext.contextNameFor("a.b_c-d"));
        LoggerContext ctx = new NodeLoggingContext("main net!x", null).loggerContext();
        assertEquals("signum-node-main_net_x", ctx.getName());
        ctx.stop();
    }

    @Test
    @DisplayName("context starts from the generated file and reconfigure() reloads the in-place rewrite (Q2b)")
    void startAndInPlaceReconfigure() throws Exception {
        Path file = minimalConfig("n1.log4j2.properties", "INFO");
        NodeLoggingContext nlc = new NodeLoggingContext("n1", file.toUri()).start();
        try {
            assertTrue(nlc.isStarted());
            assertEquals("INFO", String.valueOf(
                    nlc.loggerContext().getConfiguration().getRootLogger().getLevel()));

            Files.writeString(file, "status = ERROR\nconfigWatch = false\nrootLogger.level = DEBUG\n");
            nlc.reconfigure();
            assertEquals("DEBUG", String.valueOf(
                    nlc.loggerContext().getConfiguration().getRootLogger().getLevel()),
                    "the same context must pick up the regenerated file (Apply path)");
        } finally {
            nlc.stop();
        }
    }

    @Test
    @DisplayName("reconfigureFrom switches to a different config file (two-phase start, Q2a fallback)")
    void reconfigureFromDifferentFile() throws Exception {
        Path minimal = minimalConfig("m.log4j2.properties", "INFO");
        Path full = minimalConfig("f.log4j2.properties", "TRACE");
        NodeLoggingContext nlc = new NodeLoggingContext("n2", minimal.toUri()).start();
        try {
            assertEquals("INFO", String.valueOf(
                    nlc.loggerContext().getConfiguration().getRootLogger().getLevel()));
            nlc.reconfigureFrom(full.toUri());
            assertEquals("TRACE", String.valueOf(
                    nlc.loggerContext().getConfiguration().getRootLogger().getLevel()),
                    "the same context instance must run the full config after the switch");
            assertEquals(full.toUri(), nlc.configUri());
        } finally {
            nlc.stop();
        }
    }

    @Test
    @DisplayName("stop -> start -> reconfigure cycle is clean on the same context (Q6 via the P1 API)")
    void stopStartReconfigureCycle() throws Exception {
        Path file = minimalConfig("c.log4j2.properties", "INFO");
        NodeLoggingContext nlc = new NodeLoggingContext("n3", file.toUri()).start();
        try {
            nlc.stop();
            assertFalse(nlc.isStarted());
            nlc.start();
            assertTrue(nlc.isStarted());
            Files.writeString(file, "status = ERROR\nconfigWatch = false\nrootLogger.level = ERROR\n");
            nlc.reconfigure();
            assertEquals("ERROR", String.valueOf(
                    nlc.loggerContext().getConfiguration().getRootLogger().getLevel()),
                    "after restart the reconfigure must apply cleanly (no duplicate/closed appenders)");
        } finally {
            nlc.stop();
        }
    }

    @Test
    @DisplayName("manager: getOrCreate is idempotent, remove disposes, a later create is fresh")
    void managerLifecycle() throws Exception {
        NodeLoggingContextManager manager = NodeLoggingContextManager.ofCurrentFactory();
        Path file = minimalConfig("g.log4j2.properties", "WARN");
        NodeLoggingContext first = manager.getOrCreate("p1", file.toUri());
        try {
            NodeLoggingContext again = manager.getOrCreate("p1", file.toUri());
            org.junit.jupiter.api.Assertions.assertSame(first, again,
                    "the same profile must share one context");
            org.junit.jupiter.api.Assertions.assertSame(first, manager.get("p1"));

            assertTrue(manager.remove("p1"));
            assertFalse(first.isStarted(), "remove must stop the context");
            org.junit.jupiter.api.Assertions.assertNull(manager.get("p1"));

            NodeLoggingContext fresh = manager.getOrCreate("p1", file.toUri());
            org.junit.jupiter.api.Assertions.assertNotSame(first, fresh,
                    "after disposal a FRESH context is created");
            assertTrue(fresh.isStarted());
        } finally {
            assertTrue(manager.remove("p1"));
            assertFalse(manager.remove("p1"), "removing a non-existent profile is false");
        }
    }

    @Test
    @DisplayName("remove also clears the context from the Log4j2 factory's map")
    void removeCleansTheFactoryMap() throws Exception {
        org.apache.logging.log4j.core.impl.Log4jContextFactory factory =
                (org.apache.logging.log4j.core.impl.Log4jContextFactory)
                        org.apache.logging.log4j.LogManager.getFactory();
        NodeLoggingContextManager manager = new NodeLoggingContextManager(factory);
        Path file = minimalConfig("fm.log4j2.properties", "INFO");
        NodeLoggingContext nlc = manager.getOrCreate("p2", file.toUri());
        manager.remove("p2");
        assertFalse(factory.getSelector().getLoggerContexts().contains(nlc.loggerContext()),
                "the disposed context must not linger in the factory's context list");
    }
}