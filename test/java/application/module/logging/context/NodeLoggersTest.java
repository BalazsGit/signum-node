package application.module.logging.context;

import org.apache.logging.log4j.Logger;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * P2.1: {@link NodeLoggers} — the single source of a node's loggers (plan
 * §7.1): identity per context, cross-node separation, level decisions taken
 * by the node context's configuration only.
 */
@DisplayName("P2.1 - NodeLoggers facade")
class NodeLoggersTest {

    @TempDir
    Path tempDir;

    private NodeLoggingContext context(String file, String rootLevel) throws Exception {
        Path p = tempDir.resolve(file);
        Files.writeString(p, "# GENERATED by Signum — do not edit\n"
                + "status = ERROR\nconfigWatch = false\n"
                + "rootLogger.level = " + rootLevel + "\n");
        return new NodeLoggingContext(file, p.toUri()).start();
    }

    @Test
    @DisplayName("same name -> same instance; forClass uses the FQCN")
    void identity() throws Exception {
        NodeLoggingContext nlc = context("l1.log4j2.properties", "INFO");
        try {
            NodeLoggers loggers = new NodeLoggers(nlc.loggerContext());
            Logger a = loggers.forClass(SomeNodeComponent.class);
            Logger b = loggers.forClass(SomeNodeComponent.class);
            assertSame(a, b, "the same class must share one logger instance");
            assertSame(a, loggers.forName(SomeNodeComponent.class.getName()));
            assertNotSame(a, loggers.forName("other.Logger"));
            assertSame(nlc.loggerContext(), loggers.context());
        } finally {
            nlc.stop();
        }
    }

    @Test
    @DisplayName("two nodes, same logger name -> separate instances, separate configs")
    void separation() throws Exception {
        NodeLoggingContext debugNode = context("l2.log4j2.properties", "DEBUG");
        NodeLoggingContext warnNode = context("l3.log4j2.properties", "WARN");
        try {
            Logger inDebugNode = new NodeLoggers(debugNode.loggerContext())
                    .forClass(SomeNodeComponent.class);
            Logger inWarnNode = new NodeLoggers(warnNode.loggerContext())
                    .forClass(SomeNodeComponent.class);
            assertNotSame(inDebugNode, inWarnNode,
                    "the same name in two contexts must be two distinct instances");
            assertTrue(inDebugNode.isDebugEnabled(), "the DEBUG node's logger sees DEBUG");
            assertFalse(inWarnNode.isDebugEnabled(), "the WARN node's logger does not");
            assertTrue(inDebugNode.isInfoEnabled());
            assertTrue(inWarnNode.isWarnEnabled());
        } finally {
            debugNode.stop();
            warnNode.stop();
        }
    }

    /** A stand-in node motor class for logger-name tests. */
    static final class SomeNodeComponent {
    }
}